import { defineConfig, loadEnv } from 'vite';
import { writeFileSync, mkdirSync } from 'fs';
import path from 'path';
import react from '@vitejs/plugin-react';

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '');
  const cfgPath = path.resolve(__dirname, 'web/config.js');

  // During development, generate the config.js file dynamically
  // This allows us to use .env variables without hardcoding them.
  //
  // Built as an object and serialised with JSON.stringify rather than
  // interpolated into a template string: a value containing a quote used to
  // produce a syntactically broken config.js (and an unset variable the literal
  // string "undefined"), which fails at load time as a blank page rather than
  // as a readable error. The equivalent heredoc in docker-entrypoint.sh has the
  // same shape; it stays as it is because escaping there would mean adding jq
  // to the runtime image for values that come from the Helm chart.
  if (mode === 'development') {
    const appconfig = {
      dynamicZonesBaseUrl: env.DYNAMIC_ZONE_BASE_URL || '',
      cloudResourcesBaseUrl: env.CLOUD_RESOURCES_BASE_URL || '',
      acmeServer: env.ACME_SERVER || 'https://certificates.dhbw.cloud',
      dummyAuth: env.DUMMY_AUTH === 'true',
      oidc: {
        client_id: env.OIDC_CLIENT_ID || '',
        issuer_url: env.OIDC_ISSUER_URL || '',
      },
    };
    mkdirSync(path.dirname(cfgPath), { recursive: true });
    writeFileSync(cfgPath,
      `// Auto-generated by Vite during build (mode: ${mode}) — do not edit.\n` +
      `window.appconfig = ${JSON.stringify(appconfig, null, 2)};\n`);
  }

  return {
    root: 'web',
    // Source files are .jsx, handled natively by @vitejs/plugin-react
    // (automatic JSX runtime + React Fast Refresh in dev).
    plugins: [react()],
    build: {
      outDir: '../dist',
      emptyOutDir: true,
      rollupOptions: {
        output: {
          // Split large vendors into their own long-lived cacheable chunks
          // (swagger-ui is dynamically imported, so it already lands in its own
          // async chunk and is intentionally not listed here). vite 8 / rolldown
          // requires manualChunks to be a function, not the object map.
          manualChunks(id) {
            if (id.includes('/node_modules/@mantine/')) return 'mantine';
            if (/\/node_modules\/(react|react-dom|wouter)\//.test(id)) return 'vendor';
          },
        },
      },
    },
    server: {
      port: 8084
    },
    // Unit tests. Deliberately only the pure functions — the arithmetic and the
    // string rules that are wrong silently. Rendering is not tested, so no DOM
    // environment and no @testing-library are pulled in.
    // Paths are relative to `root` above, i.e. web/.
    test: {
      environment: 'node',
      include: ['**/*.test.js'],
    },
    define: {
      __APP_VERSION__: JSON.stringify(process.env.npm_package_version),
    },
    clearScreen: true
  };
});
